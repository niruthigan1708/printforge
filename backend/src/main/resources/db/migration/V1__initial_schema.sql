-- Initial PrintForge schema.
--
-- This reproduces exactly what Hibernate's ddl-auto created before Flyway was adopted,
-- including its generated constraint names, so databases created either way are identical.
-- Existing databases are baselined at version 1 (spring.flyway.baseline-on-migrate) and never
-- run this script; new databases run it on first start.
--
-- Written to run on PostgreSQL and on H2 in PostgreSQL mode (used by the test suite).

CREATE TABLE users (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    created_at timestamp(6) with time zone,
    email varchar(255) NOT NULL,
    name varchar(255) NOT NULL,
    password varchar(255) NOT NULL,
    role varchar(255) NOT NULL,
    CONSTRAINT users_pkey PRIMARY KEY (id),
    CONSTRAINT uk6dotkott2kjsp8vw4d0m25fb7 UNIQUE (email),
    CONSTRAINT users_role_check CHECK (role IN ('CUSTOMER', 'ADMIN'))
);

CREATE TABLE category (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    description varchar(255),
    name varchar(255) NOT NULL,
    CONSTRAINT category_pkey PRIMARY KEY (id),
    CONSTRAINT uk46ccwnsi9409t36lurvtyljak UNIQUE (name)
);

CREATE TABLE product (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    active boolean NOT NULL,
    color varchar(255) NOT NULL,
    created_at timestamp(6) with time zone,
    description varchar(2000) NOT NULL,
    image_url text,
    material varchar(255) NOT NULL,
    name varchar(255) NOT NULL,
    price numeric(12,2) NOT NULL,
    stock_quantity integer NOT NULL,
    updated_at timestamp(6) with time zone,
    category_id bigint NOT NULL,
    CONSTRAINT product_pkey PRIMARY KEY (id),
    CONSTRAINT product_stock_quantity_check CHECK (stock_quantity >= 0),
    CONSTRAINT fk1mtsbur82frn64de7balymq9s FOREIGN KEY (category_id) REFERENCES category (id)
);

CREATE TABLE customer_orders (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    created_at timestamp(6) with time zone,
    delivery_fee numeric(38,2),
    order_number varchar(255) NOT NULL,
    shipping_address varchar(255),
    shipping_city varchar(255),
    shipping_name varchar(255),
    shipping_phone varchar(255),
    shipping_postal_code varchar(255),
    status varchar(255),
    subtotal numeric(38,2),
    total_amount numeric(38,2),
    updated_at timestamp(6) with time zone,
    customer_id bigint NOT NULL,
    CONSTRAINT customer_orders_pkey PRIMARY KEY (id),
    CONSTRAINT uks4wt1sgd48rj6cgahwlksogx UNIQUE (order_number),
    CONSTRAINT customer_orders_status_check CHECK (status IN ('PENDING', 'CONFIRMED', 'PRINTING', 'READY', 'SHIPPED', 'DELIVERED', 'CANCELLED')),
    CONSTRAINT fk6l43qmx85kv98oigli25si8xh FOREIGN KEY (customer_id) REFERENCES users (id)
);

CREATE TABLE order_item (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    product_name varchar(255),
    quantity integer NOT NULL,
    subtotal numeric(38,2),
    unit_price numeric(38,2),
    order_id bigint NOT NULL,
    product_id bigint NOT NULL,
    CONSTRAINT order_item_pkey PRIMARY KEY (id),
    CONSTRAINT fkmkduiirt9s4xnqq08hxi9lser FOREIGN KEY (order_id) REFERENCES customer_orders (id),
    CONSTRAINT fk551losx9j75ss5d6bfsqvijna FOREIGN KEY (product_id) REFERENCES product (id)
);

CREATE TABLE custom_print_request (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    admin_notes varchar(2000),
    admin_quote numeric(38,2),
    color varchar(255) NOT NULL,
    created_at timestamp(6) with time zone,
    file_name varchar(255) NOT NULL,
    file_path varchar(255) NOT NULL,
    file_type varchar(255) NOT NULL,
    material varchar(255) NOT NULL,
    notes varchar(2000),
    quantity integer NOT NULL,
    request_number varchar(255) NOT NULL,
    status varchar(255),
    updated_at timestamp(6) with time zone,
    customer_id bigint NOT NULL,
    CONSTRAINT custom_print_request_pkey PRIMARY KEY (id),
    CONSTRAINT ukk7pja42hxas40p1o0egtm7fe9 UNIQUE (request_number),
    CONSTRAINT custom_print_request_status_check CHECK (status IN ('SUBMITTED', 'UNDER_REVIEW', 'QUOTED', 'ACCEPTED', 'REJECTED', 'IN_PRODUCTION', 'COMPLETED', 'CANCELLED')),
    CONSTRAINT fkeg8u2f3ydi2h71jg2ha2gqu67 FOREIGN KEY (customer_id) REFERENCES users (id)
);

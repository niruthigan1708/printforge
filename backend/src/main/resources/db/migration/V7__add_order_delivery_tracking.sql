-- Delivery accountability for orders.
--   tracking_number   required when an order is marked SHIPPED, shown to the customer
--   delivered_at      when it was marked DELIVERED (starts the 14-day window for reporting a problem)
--   received_at       when the customer confirmed they received it
--   issue_*           an open or resolved "I haven't received this" report from the customer
ALTER TABLE customer_orders ADD COLUMN tracking_number varchar(100);
ALTER TABLE customer_orders ADD COLUMN delivered_at timestamp(6) with time zone;
ALTER TABLE customer_orders ADD COLUMN received_at timestamp(6) with time zone;
ALTER TABLE customer_orders ADD COLUMN issue_reported_at timestamp(6) with time zone;
ALTER TABLE customer_orders ADD COLUMN issue_note varchar(2000);
ALTER TABLE customer_orders ADD COLUMN issue_resolved_at timestamp(6) with time zone;
ALTER TABLE customer_orders ADD COLUMN issue_resolution varchar(2000);

-- Orders already delivered before this migration: their delivery time is the last update.
UPDATE customer_orders SET delivered_at = updated_at WHERE status = 'DELIVERED';

-- Every change to an order, who made it and when. Actor details are copied (not referenced) so the
-- history stays readable even if an account is later renamed.
CREATE TABLE order_event (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    order_id bigint NOT NULL,
    event_type varchar(30) NOT NULL,
    status varchar(30),
    actor_name varchar(255),
    actor_email varchar(255),
    actor_role varchar(20),
    note varchar(2000),
    created_at timestamp(6) with time zone NOT NULL,
    CONSTRAINT order_event_pkey PRIMARY KEY (id),
    CONSTRAINT order_event_type_check CHECK (event_type IN ('PLACED', 'STATUS_CHANGED', 'RECEIVED', 'ISSUE_REPORTED', 'ISSUE_RESOLVED')),
    CONSTRAINT fk_order_event_order FOREIGN KEY (order_id) REFERENCES customer_orders (id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_order_event_order_id ON order_event (order_id);

-- Give existing orders a starting point: when they were placed, and (if they have moved on since)
-- their current status at their last update. Who made that change was never recorded.
INSERT INTO order_event (order_id, event_type, status, actor_name, actor_email, actor_role, created_at)
SELECT o.id, 'PLACED', 'PENDING', u.name, u.email, 'CUSTOMER', COALESCE(o.created_at, CURRENT_TIMESTAMP)
FROM customer_orders o JOIN users u ON u.id = o.customer_id;

INSERT INTO order_event (order_id, event_type, status, note, created_at)
SELECT o.id, 'STATUS_CHANGED', o.status, 'Recorded before order history was kept', COALESCE(o.updated_at, o.created_at, CURRENT_TIMESTAMP)
FROM customer_orders o WHERE o.status <> 'PENDING';
